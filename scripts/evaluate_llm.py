"""Evaluate the insight generator over many months of data.

    python scripts/evaluate_llm.py                       # uses your .env key if present, else the rule-based fallback
    python scripts/evaluate_llm.py --max-months 12 --input data/sales_data.xlsx

Writes reports/llm_evaluation.csv and reports/llm_evaluation.md (paste the table into your project report).
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.data_ingestion import load_dataset
from src.evaluation import evaluate_generator, summarize
from src.llm_generator import LLMConfig, generate_insights
from src.pipeline import prepare_dataset, run_analysis


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", default=str(ROOT / "data" / "sales_data.xlsx"))
    ap.add_argument("--max-months", type=int, default=12, help="evaluate the most recent N months")
    ap.add_argument("--currency", default="INR")
    ap.add_argument("--delay", type=float, default=3.0, help="seconds to wait between LLM calls (free tiers are rate limited)")
    args = ap.parse_args()

    clean, _ = prepare_dataset(load_dataset(args.input))
    months = sorted(clean["Date"].dt.to_period("M").unique())[1:][-args.max_months:]
    payloads = {str(m): run_analysis(clean, m, currency=args.currency).payload for m in months}
    cfg = LLMConfig.from_env()
    using_llm = bool(cfg.api_key and cfg.api_key != "your_key_here")
    print(f"Evaluating {len(payloads)} months with {'LLM ' + cfg.model if using_llm else 'rule-based fallback (no API key found)'} ...")

    def generate(payload):
        # With a real LLM configured, a failed call must count as a FAILURE. If we silently used the rule-based
        # fallback here, the table would score the fallback and wrongly look like an LLM result.
        result = generate_insights(payload, cfg, allow_fallback=not using_llm)
        if using_llm and args.delay:
            time.sleep(args.delay)
        return result

    df = evaluate_generator(generate, payloads)
    s = summarize(df)

    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    df.to_csv(out / "llm_evaluation.csv")
    label = f"LLM `{cfg.model}`" if using_llm else "rule-based fallback (no API key)"
    lines = [f"# LLM Evaluation: {label}", "", f"Months evaluated: {s['reports']} (from `{Path(args.input).name}`)", "",
             "| Metric | Result | Goal |", "|---|---|---|",
             f"| Reports really generated by the LLM | {s['from_llm']} of {s['reports']} (fallback: {s['from_fallback']}, failed: {s['failed']}) | all |",
             f"| Valid JSON schema | {s['schema_valid_pct']:.0f}% | 100% |",
             f"| Unsupported-number rate (hallucination) | {s['unsupported_number_rate_pct']:.1f}% | 0% |",
             f"| Top-driver coverage | {s['avg_driver_coverage_pct']:.0f}% | high |",
             f"| Top-decline coverage | {s['avg_decline_coverage_pct']:.0f}% | high |",
             f"| Causal phrases (unsupported causes) | {s['causal_phrases_total']} | 0 |",
             f"| Recommendations leaking into fact sections | {s['reco_leakage_total']} | 0 |", "",
             "## Per month", "", df.round(1).to_markdown() if hasattr(df, "to_markdown") and _has_tabulate() else df.round(1).to_string()]
    (out / "llm_evaluation.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:13]))
    if using_llm and s["from_llm"] < s["reports"]:
        print(f"\nWARNING: only {s['from_llm']} of {s['reports']} reports came from the LLM. The AI service failed for the rest "
              "(see the 'error' column in reports/llm_evaluation.csv). Wait a few minutes and run again.")
    return 0


def _has_tabulate() -> bool:
    try:
        import tabulate  # noqa: F401
        return True
    except ImportError:
        return False


if __name__ == "__main__":
    sys.exit(main())
